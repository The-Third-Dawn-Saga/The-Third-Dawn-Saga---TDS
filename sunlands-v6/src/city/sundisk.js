/** The Royal Palace: 50 acres of interconnected buildings around courtyards. */
function buildPalace(material) {
  const geo = geometryKit();
  const set = new InstanceSet(geo.house, material, 128);
  const rng = makeRng(seedFrom('palace'));

  /* Six courtyards on a rough grid, wings between them. Not one block: canon
     is explicit that the palace is interconnected buildings around courts. */
  const courts = [
    [0, 0, 120, 120], [-180, -140, 90, 80], [180, -140, 90, 80],
    [-180, 150, 90, 80], [180, 150, 90, 80], [0, 250, 110, 70],
  ];
  for (const [cx, cz, cw, cd] of courts) {
    const wing = 26 + rng() * 8;
    const h = 11 + rng() * 6;
    const gold = goldRatio(Math.hypot(cx, cz), 1.0, 0.95);
    /* Four wings around the court. */
    set.add(cx, G, cz - cd / 2 - wing / 2, cw + wing * 2, h, wing, 0, gold, 0.8, 0.05);
    set.add(cx, G, cz + cd / 2 + wing / 2, cw + wing * 2, h, wing, 0, gold, 0.8, 0.05);
    set.add(cx - cw / 2 - wing / 2, G, cz, wing, h, cd, 0, gold, 0.8, 0.05);
    set.add(cx + cw / 2 + wing / 2, G, cz, wing, h, cd, 0, gold, 0.8, 0.05);
  }

  /* THE THRONE ROOM. Faces east to catch first light, with the dais at the
     origin, so at dawn the sun really does come in through the aperture and
     strike it. The east wall is left open as a colonnade rather than closed,
     which is what makes that true rather than decorative. */
  const throneW = 78, throneD = 54, throneH = 22;
  set.add(-throneW / 2 - 6, G, 0, 12, throneH, throneD + 24, 0, 1.0, 0.9, 0.02);  // west wall
  set.add(0, G, -throneD / 2 - 6, throneW, throneH, 12, 0, 1.0, 0.9, 0.02);       // north wall
  set.add(0, G, throneD / 2 + 6, throneW, throneH, 12, 0, 1.0, 0.9, 0.02);        // south wall
  /* Eastern colonnade: piers with the aperture between them. */
  for (let i = -3; i <= 3; i++) {
    if (i === 0) continue;                     // the aperture itself
    set.add(throneW / 2 + 4, G, i * 7.6, 6, throneH, 4.4, 0, 1.0, 0.95, 0.02);
  }
  /* The dais. Its top surface centre is the origin of the world. */
  set.add(0, G, 0, 14, -G, 14, 0, 1.0, 1.0, 0.0);

  /* The Sunset Wing, on the west face. */
  set.add(-340, G, 0, 60, 15, 150, 0, goldRatio(340, 1.0, 0.9), 0.85, 0.05);

  const mesh = set.build('palace');
  const grp = new THREE.Group();
  if (mesh) grp.add(mesh);
  grp.name = 'royal-palace';
  return grp;
}

/**
 * The Great Sun Temple, in the Djenne form language: mud-brick mass,
 * projecting toron beams in regular rows, tapering buttress pilasters,
 * rounded parapets, and three towers for dawn, noon and dusk, each capped
 * with an ostrich-egg pinnacle.
 */
function buildTemple(material) {
  const geo = geometryKit();
  const body = new InstanceSet(geo.house, material, 512);
  const eggs = new InstanceSet(geo.egg, material, 8);
  const rng = makeRng(seedFrom('sun-temple'));

  const cx = 520, cz = -180;
  const W = 132, D = 96, H = 17;          // capacity 10,000 at the canon figure
  const gold = goldRatio(Math.hypot(cx, cz), 1.0, 1.0);

  body.add(cx, G, cz, W, H, D, 0, gold * 0.8, 0.72, 0.12);

  /* Tapering buttress pilasters down every face, the Djenne signature. */
  const pil = 3.4;
  for (let i = -6; i <= 6; i++) {
    const px = cx + i * (W / 13);
    body.add(px, G, cz - D / 2 - pil / 2, pil, H * 1.14, pil, 0, gold * 0.85, 0.7, 0.1);
    body.add(px, G, cz + D / 2 + pil / 2, pil, H * 1.14, pil, 0, gold * 0.85, 0.7, 0.1);
  }
  for (let j = -4; j <= 4; j++) {
    const pz = cz + j * (D / 9);
    body.add(cx - W / 2 - pil / 2, G, pz, pil, H * 1.14, pil, 0, gold * 0.85, 0.7, 0.1);
    body.add(cx + W / 2 + pil / 2, G, pz, pil, H * 1.14, pil, 0, gold * 0.85, 0.7, 0.1);
  }

  /* Toron: palm beams projecting from the walls in regular rows. They are the
     permanent scaffolding the annual replastering is done from, so they are
     structural, not ornament. */
  for (let row = 0; row < 3; row++) {
    const y = G + 5 + row * 4.4;
    for (let i = -8; i <= 8; i++) {
      const px = cx + i * (W / 17);
      body.add(px, y, cz - D / 2 - 0.9, 0.32, 0.32, 2.6, 0, 0, 0.25, 0.4);
      body.add(px, y, cz + D / 2 + 0.9, 0.32, 0.32, 2.6, 0, 0, 0.25, 0.4);
    }
    for (let j = -5; j <= 5; j++) {
      const pz = cz + j * (D / 11);
      body.add(cx - W / 2 - 0.9, y, pz, 2.6, 0.32, 0.32, 0, 0, 0.25, 0.4);
      body.add(cx + W / 2 + 0.9, y, pz, 2.6, 0.32, 0.32, 0, 0, 0.25, 0.4);
    }
  }

  /* Three towers: dawn, noon and dusk. Dawn faces east. */
  const towers = [
    { dx: W / 2 - 12, dz: 0, h: 34, name: 'dawn' },
    { dx: 0, dz: -D / 2 + 10, h: 40, name: 'noon' },
    { dx: -W / 2 + 12, dz: 0, h: 34, name: 'dusk' },
  ];
  for (const t of towers) {
    body.add(cx + t.dx, G, cz + t.dz, 15, t.h, 15, 0, gold, 0.78, 0.08);
    eggs.add(cx + t.dx, G + t.h, cz + t.dz, 5.4, 5.4, 5.4, 0, 1.0, 1.0, 0.0);
  }

  const grp = new THREE.Group();
  const b = body.build('temple');
  const e = eggs.build('temple-pinnacles');
  if (b) grp.add(b);
  if (e) grp.add(e);
  grp.name = 'great-sun-temple';
  return grp;
}

/** Seven great families, seven minor palaces, each competing. */
function buildNobleQuarter(material) {
  const geo = geometryKit();
  const set = new InstanceSet(geo.house, material, 256);
  const rng = makeRng(seedFrom('noble-quarter'));
  for (let f = 0; f < 7; f++) {
    const a = (f / 7) * Math.PI * 2 + 0.4;
    const rr = 820 + rng() * 180;
    const cx = Math.cos(a) * rr, cz = Math.sin(a) * rr;
    /* Each family gets a distinct massing and a distinct gold ratio, because
       the competition between them is the point. */
    const style = f % 3;
    const wealth = 0.78 + (f % 5) * 0.045;
    const gold = goldRatio(rr, wealth, 0.9);
    const n = 4 + style;
    for (let i = 0; i < n; i++) {
      const ia = (i / n) * Math.PI * 2;
      const ir = 34 + style * 10;
      set.add(cx + Math.cos(ia) * ir, G, cz + Math.sin(ia) * ir,
        22 + rng() * 12, 10 + style * 4 + rng() * 5, 18 + rng() * 10,
        ia, gold, 0.7 + rng() * 0.3, 0.04 + rng() * 0.08);
    }
    /* The walled garden, which is what the water is actually for. */
    for (let s = 0; s < 4; s++) {
      const sa = s * Math.PI / 2;
      set.add(cx + Math.cos(sa) * 72, G, cz + Math.sin(sa) * 72,
        s % 2 ? 3 : 144, 4.2, s % 2 ? 144 : 3, 0, gold * 0.5, 0.6, 0.1);
    }
  }
  const grp = new THREE.Group();
  const m = set.build('noble-quarter');
  if (m) grp.add(m);
  return grp;
}


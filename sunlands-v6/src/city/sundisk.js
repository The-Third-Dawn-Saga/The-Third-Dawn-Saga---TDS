export function buildSundiskFull(ctx) {
  const grp = new THREE.Group();
  grp.name = 'sundisk-full';
  const mat = ctx.sunklay;

  const data = generateCity({ detail: 1 });
  const city = buildInstances(data, mat, 12);
  grp.add(city);

  grp.add(buildPalace(mat));
  grp.add(buildTemple(mat));
  grp.add(buildNobleQuarter(mat));
  grp.add(buildGranaries(mat));
  grp.add(buildMarket(mat));
  grp.add(buildAcademy(mat));

  if (ctx.buildWall) grp.add(ctx.buildWall(ctx));
  if (ctx.buildVeil) grp.add(ctx.buildVeil(ctx));
  if (ctx.buildWater) grp.add(ctx.buildWater(ctx));
  if (ctx.buildCrowd) grp.add(ctx.buildCrowd(CITY));

  grp.userData.instanceCount = city.userData.instanceCount;
  /* The generator's own building list, handed to the character controller so
     collision is a 2D box test against a grid rather than a raycast against
     thirty-four thousand instances. */
  grp.userData.collisionRects = data.houses.map(h => ({
    x: h.x, z: h.z, w: h.w, d: h.d, h: h.h, rot: h.rot, baseY: G,
  }));
  return grp;
}


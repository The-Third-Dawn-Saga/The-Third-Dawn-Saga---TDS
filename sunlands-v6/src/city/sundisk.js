/**
 * Beyond eight kilometres the city is a footprint, not buildings: the glowing
 * extent Part 1.4 asks for at Kingdom tier, with the wall ring reading as a
 * hard edge and the Commons as a spreading stain outside it.
 */
export function buildSundiskImposter(ctx) {
  const grp = new THREE.Group();
  grp.name = 'sundisk-imposter';

  const disc = (r0, r1, color, opacity, y) => {
    const g = new THREE.RingGeometry(r0, r1, 96, 1);
    g.rotateX(-Math.PI / 2);
    const m = new THREE.MeshBasicMaterial({
      color, transparent: true, opacity, depthWrite: false, side: THREE.DoubleSide,
    });
    m.userData.ownedByRegion = true;
    const mesh = new THREE.Mesh(g, m);
    mesh.position.y = CITY_GROUND_Y + y;
    mesh.renderOrder = 2;
    return mesh;
  };

  grp.add(disc(0, CITY.inner, 0xd9a83a, 0.85, 3.0));
  grp.add(disc(CITY.inner, CITY.middle, 0xa07f42, 0.72, 2.6));
  grp.add(disc(CITY.middle, CITY.outer, 0x7d6647, 0.66, 2.2));
  grp.add(disc(CITY.outer, CITY.outer + 26, 0xe8c46a, 0.9, 3.4));      // the wall itself
  grp.add(disc(CITY.outer + 26, CITY.commons, 0x5d5040, 0.44, 1.8));   // the Commons

  return grp;
}
